/** Equirectangular projection of the painted maps. */
function projector(w: number, h: number) {
  return (lon: number, lat: number): [number, number] => {
    let u = (lon - LON0) / 360 + 0.25;
    u -= Math.floor(u);
    return [u * w, ((90 - lat) / 180) * h];
  };
}

/** Trace an outline three times (wrapped) so shapes crossing the seam are complete. */
function tracePolygon(g: CanvasRenderingContext2D, outline: Outline, w: number, h: number) {
  const first = ((outline[0] - LON0) / 360 + 0.25) * w;
  const shift = -Math.floor(first / w) * w;
  for (const offset of [-w, 0, w]) {
    g.beginPath();
    for (let i = 0; i < outline.length; i += 2) {
      const x = ((outline[i] - LON0) / 360 + 0.25) * w + shift + offset;
      const y = ((90 - outline[i + 1]) / 180) * h;
      if (i === 0) g.moveTo(x, y);
      else g.lineTo(x, y);
    }
    g.closePath();
    g.fill();
  }
}

/** A flat, organic patch (hand-drawn looking outline) in longitude/latitude. */
function paintPatch(g: CanvasRenderingContext2D, w: number, h: number, patch: Patch, seed: number) {
  const [lon, lat, rlon, rlat, color] = patch;
  const random = rng(seed * 97 + 13);
  const harmonics = [2, 3, 5, 7].map((k) => ({ k, a: (random() - 0.5) * (0.5 / Math.sqrt(k)), p: random() * Math.PI * 2 }));
  const px = w / 360;
  const py = h / 180;
  let u = (lon - LON0) / 360 + 0.25;
  u -= Math.floor(u);
  g.fillStyle = color;
  for (const offset of [-w, 0, w]) {
    const x = u * w + offset;
    const y = ((90 - lat) / 180) * h;
    g.beginPath();
    for (let i = 0; i <= 48; i++) {
      const a = (i / 48) * Math.PI * 2;
      let r = 1;
      for (const hm of harmonics) r += hm.a * Math.sin(hm.k * a + hm.p);
      const pxl = x + Math.cos(a) * rlon * px * r;
      const pyl = y + Math.sin(a) * rlat * py * r;
      if (i === 0) g.moveTo(pxl, pyl);
      else g.lineTo(pxl, pyl);
    }
    g.fill();
  }
}

/** Paint the day-side colour map. */
export function paintEarth(g: CanvasRenderingContext2D, w: number, h: number) {
  // Oceans: brighter near the equator, deeper towards the poles.
  const ocean = g.createLinearGradient(0, 0, 0, h);
  ocean.addColorStop(0, "#2a55c4");
  ocean.addColorStop(0.3, "#2f6fe0");
  ocean.addColorStop(0.5, "#3a82ef");
  ocean.addColorStop(0.72, "#2f6fe0");
  ocean.addColorStop(1, "#2a55c4");
  g.fillStyle = ocean;
  g.fillRect(0, 0, w, h);

  // Land on its own layer, so biomes can be painted over land only.
  const land = document.createElement("canvas");
  land.width = w;
  land.height = h;
  const l = land.getContext("2d")!;
  l.fillStyle = "#5dc463";
  for (const outline of LAND) tracePolygon(l, outline, w, h);
  l.fillStyle = "#eef4ff";
  tracePolygon(l, ANTARCTICA, w, h);
  l.globalCompositeOperation = "source-atop";
  BIOMES.forEach((patch, k) => paintPatch(l, w, h, patch, k));
  // High Arctic: pale and icy.
  const polar = l.createLinearGradient(0, 0, 0, h * 0.14);
  polar.addColorStop(0, "rgba(238,244,255,1)");
  polar.addColorStop(0.72, "rgba(238,244,255,1)");
  polar.addColorStop(0.86, "rgba(214,232,210,0.9)");
  polar.addColorStop(1, "rgba(200,225,190,0)");
  l.fillStyle = polar;
  l.fillRect(0, 0, w, h * 0.14);
  SNOW.forEach((patch, k) => paintPatch(l, w, h, patch, 100 + k));
  l.fillStyle = "#eef4ff";
  tracePolygon(l, GREENLAND, w, h);
  l.globalCompositeOperation = "source-over";

  // Shallow coastal shelves: a soft light-blue halo around the land.
  g.save();
  g.filter = `blur(${Math.max(1, w / 400)}px)`;
  g.globalAlpha = 0.9;
  g.drawImage(tintedCopy(land, "#5aa8ff", Math.max(1, w / 520)), 0, 0);
  g.restore();
  g.drawImage(land, 0, 0);

  // Inland seas and lakes.
  g.fillStyle = "#3a82ef";
  for (const outline of WATER) tracePolygon(g, outline, w, h);

  // Polar sea ice (north): a crisp, wobbly cap.
  g.fillStyle = "#e3eeff";
  g.beginPath();
  g.moveTo(-10, -10);
  for (let x = -10; x <= w + 10; x += w / 180) {
    const lon = (x / w - 0.25) * 360 + LON0;
    const lat = 80 + Math.sin(lon * 0.09) * 1.6 + Math.sin(lon * 0.23 + 1) * 0.9;
    g.lineTo(x, ((90 - lat) / 180) * h);
  }
  g.lineTo(w + 10, -10);
  g.closePath();
  g.fill();
}

/** A copy of `source` where every opaque pixel is `color`, dilated by `grow` pixels. */
function tintedCopy(source: HTMLCanvasElement, color: string, grow: number) {
  const canvas = document.createElement("canvas");
  canvas.width = source.width;
  canvas.height = source.height;
  const g = canvas.getContext("2d")!;
  for (const [dx, dy] of [
    [grow, 0],
    [-grow, 0],
    [0, grow],
    [0, -grow],
    [0, 0],
  ])
    g.drawImage(source, dx, dy);
  g.globalCompositeOperation = "source-in";
  g.fillStyle = color;
  g.fillRect(0, 0, canvas.width, canvas.height);
  return canvas;
}

/** City lights (red channel) and ocean mask (green channel). */
